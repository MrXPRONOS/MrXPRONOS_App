-- Observabilité Actu Foot. Table privée, écrite uniquement par les runners service-role.
create table if not exists public.actu_foot_run_metrics (
  id bigint generated by default as identity primary key,
  run_id text,
  mode text not null check (mode in ('full','lifecycle')),
  dry_run boolean not null default false,
  started_at timestamptz not null,
  finished_at timestamptz not null,
  duration_ms integer not null default 0,
  sent integer not null default 0,
  skipped integer not null default 0,
  errors integer not null default 0,
  tracked_pending integer not null default 0,
  ranking_eligible integer not null default 0,
  ranking_selected integer not null default 0,
  outbox_pending integer not null default 0,
  ranking_snapshot jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists actu_foot_run_metrics_finished_idx
  on public.actu_foot_run_metrics(finished_at desc);
create index if not exists actu_foot_run_metrics_mode_finished_idx
  on public.actu_foot_run_metrics(mode, finished_at desc);

alter table public.actu_foot_run_metrics enable row level security;
revoke all on table public.actu_foot_run_metrics from anon, authenticated;
grant select, insert, update, delete on table public.actu_foot_run_metrics to service_role;
