-- Assistant V2: backend-only security, feedback review, verified FAQ
-- This migration records safeguards applied manually to Supabase before merging.
-- It is idempotent except for the trigger replacement.
CREATE TABLE IF NOT EXISTS public.assistant_review_queue (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  feedback_id bigint REFERENCES public.feedback(id) ON DELETE SET NULL,
  question text NOT NULL,
  response_text text,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending','approved','rejected')),
  created_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz
);
ALTER TABLE public.assistant_review_queue ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.assistant_review_queue FROM anon,authenticated;
CREATE INDEX IF NOT EXISTS assistant_review_queue_status_idx
  ON public.assistant_review_queue (status,created_at DESC);
CREATE OR REPLACE FUNCTION public.assistant_queue_bad_feedback()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF NEW.feedback IS FALSE AND LENGTH(COALESCE(NEW.question,''))>0 THEN
    INSERT INTO public.assistant_review_queue(feedback_id,question,response_text)
    VALUES(NEW.id,LEFT(NEW.question,1200),LEFT(NEW.reponse,8000));
  END IF;
  RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS assistant_queue_feedback_trigger ON public.feedback;
CREATE TRIGGER assistant_queue_feedback_trigger AFTER INSERT ON public.feedback
FOR EACH ROW EXECUTE FUNCTION public.assistant_queue_bad_feedback();

-- Backend-only tables: direct client roles should not be able to read internal logs.
ALTER TABLE public.conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vip_login_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.worker_locks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.faq ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.conversations FROM anon,authenticated;
REVOKE ALL ON public.vip_login_attempts FROM anon,authenticated;
REVOKE ALL ON public.worker_locks FROM anon,authenticated;
REVOKE ALL ON public.faq FROM anon,authenticated;
