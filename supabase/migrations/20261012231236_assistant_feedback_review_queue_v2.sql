create table if not exists public.assistant_review_queue (
 id bigint generated by default as identity primary key,
 feedback_id bigint references public.feedback(id) on delete set null,
 question text not null,
 response_text text,
 status text not null default 'pending' check (status in ('pending','approved','rejected')),
 created_at timestamptz not null default now(),
 reviewed_at timestamptz
);
alter table public.assistant_review_queue enable row level security;
revoke all on public.assistant_review_queue from anon, authenticated;
create index if not exists assistant_review_queue_status_idx on public.assistant_review_queue(status,created_at desc);
create or replace function public.assistant_queue_bad_feedback() returns trigger language plpgsql security definer set search_path = public as $$
begin
 if new.feedback is false and length(coalesce(new.question,''))>0 then
   insert into public.assistant_review_queue(feedback_id,question,response_text)
   values(new.id,left(new.question,1200),left(new.reponse,8000));
 end if;
 return new;
end; $$;
drop trigger if exists assistant_queue_feedback_trigger on public.feedback;
create trigger assistant_queue_feedback_trigger after insert on public.feedback
for each row execute function public.assistant_queue_bad_feedback();
